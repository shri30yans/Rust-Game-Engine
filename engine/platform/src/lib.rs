/// Defines the one game process entry point while keeping platform attributes in this crate.
#[macro_export]
macro_rules! platform_game_main {
    ($entry:ty, $runner:expr) => {
        #[cfg(not(target_os = "android"))]
        #[allow(dead_code)]
        fn main() {
            if let Err(error) = ($runner)($crate::ContentSource::desktop()) {
                eprintln!("{}: {error}", stringify!($entry));
                std::process::exit(1);
            }
        }

        #[cfg(target_os = "android")]
        #[allow(unsafe_code)]
        // SAFETY: NativeActivity resolves this exact exported symbol and winit supplies the
        // AndroidApp argument with the matching Rust entry contract.
        #[unsafe(no_mangle)]
        #[doc = "NativeActivity entry generated by the engine-owned game startup macro."]
        pub fn android_main(android: $crate::AndroidApp) {
            if let Err(error) = ($runner)($crate::ContentSource::android(android)) {
                $crate::log_error(&format!("{}: {error}", stringify!($entry)));
            }
        }
    };
}

/// What the platform drives. One implementation: `engine::Engine`.
pub trait PlatformApp {
    /// GPU and target format are ready (called once, before the first frame).
    fn init(&mut self, gpu: &Gpu, format: wgpu::TextureFormat, size: (u32, u32));
    /// The render target changed size; `size` is in physical pixels.
    fn resize(&mut self, size: (u32, u32));
    /// The OS revoked the presentation surface.
    fn suspend(&mut self) {}
    /// A presentation surface is available again after suspension.
    fn resume(&mut self, _gpu: &Gpu, _format: wgpu::TextureFormat, size: (u32, u32)) {
        self.resize(size);
    }
    /// The swapchain was configured for this surface session (see [`PresentationBinding`]).
    fn on_presentation_bound(&mut self, _binding: PresentationBinding) {}
    /// Draw one frame into `target`. `dt` is wall seconds since the last frame.
    fn frame(&mut self, target: &wgpu::TextureView, input: &mut Input, dt: f32);
}

/// Lets a runner borrow an app (`&mut app`) and keep ownership of it, for example to read
/// its error after the window loop returns. Every method forwards to the referenced app.
impl<T: PlatformApp + ?Sized> PlatformApp for &mut T {
    fn init(&mut self, gpu: &Gpu, format: wgpu::TextureFormat, size: (u32, u32)) {
        (**self).init(gpu, format, size);
    }
    fn resize(&mut self, size: (u32, u32)) {
        (**self).resize(size);
    }
    fn suspend(&mut self) {
        (**self).suspend();
    }
    fn resume(&mut self, gpu: &Gpu, format: wgpu::TextureFormat, size: (u32, u32)) {
        (**self).resume(gpu, format, size);
    }
    fn on_presentation_bound(&mut self, binding: PresentationBinding) {
        (**self).on_presentation_bound(binding);
    }
    fn frame(&mut self, target: &wgpu::TextureView, input: &mut Input, dt: f32) {
        (**self).frame(target, input, dt);
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)]
mod tests {
    use super::*;

    /// Records which methods were called and with what arguments.
    #[derive(Default)]
    struct Recorder {
        inits: u32,
        resizes: Vec<(u32, u32)>,
        suspends: u32,
        resumes: Vec<(u32, u32)>,
        bindings: Vec<PresentationBinding>,
        frames: Vec<f32>,
    }

    impl PlatformApp for Recorder {
        fn init(&mut self, _gpu: &Gpu, _format: wgpu::TextureFormat, _size: (u32, u32)) {
            self.inits += 1;
        }
        fn resize(&mut self, size: (u32, u32)) {
            self.resizes.push(size);
        }
        fn suspend(&mut self) {
            self.suspends += 1;
        }
        fn resume(&mut self, _gpu: &Gpu, _format: wgpu::TextureFormat, size: (u32, u32)) {
            self.resumes.push(size);
        }
        fn on_presentation_bound(&mut self, binding: PresentationBinding) {
            self.bindings.push(binding);
        }
        fn frame(&mut self, _target: &wgpu::TextureView, _input: &mut Input, dt: f32) {
            self.frames.push(dt);
        }
    }

    /// Calls every method through the `&mut T` impl, not through `Recorder` directly.
    fn drive<A: PlatformApp>(mut app: A, gpu: &Gpu, view: &wgpu::TextureView) {
        <A as PlatformApp>::init(&mut app, gpu, headless::FORMAT, (4, 4));
        <A as PlatformApp>::resize(&mut app, (8, 6));
        <A as PlatformApp>::suspend(&mut app);
        <A as PlatformApp>::resume(&mut app, gpu, headless::FORMAT, (12, 10));
        <A as PlatformApp>::on_presentation_bound(
            &mut app,
            PresentationBinding {
                intended_present_hz: Some(120.0),
                declared: true,
            },
        );
        let mut input = Input::default();
        <A as PlatformApp>::frame(&mut app, view, &mut input, 0.25);
    }

    #[test]
    fn borrowed_app_forwards_every_method() {
        let gpu = Gpu::new(wgpu::Instance::default(), None).expect("a GPU adapter is required");
        let texture = gpu.device.create_texture(&wgpu::TextureDescriptor {
            label: Some("forwarding-test"),
            size: wgpu::Extent3d {
                width: 4,
                height: 4,
                depth_or_array_layers: 1,
            },
            mip_level_count: 1,
            sample_count: 1,
            dimension: wgpu::TextureDimension::D2,
            format: headless::FORMAT,
            usage: wgpu::TextureUsages::RENDER_ATTACHMENT,
            view_formats: &[],
        });
        let view = texture.create_view(&wgpu::TextureViewDescriptor::default());
        let mut recorder = Recorder::default();
        drive(&mut recorder, &gpu, &view);
        assert_eq!(recorder.inits, 1);
        assert_eq!(recorder.resizes, vec![(8, 6)]);
        assert_eq!(recorder.suspends, 1);
        assert_eq!(recorder.resumes, vec![(12, 10)]);
        assert_eq!(
            recorder.bindings,
            vec![PresentationBinding {
                intended_present_hz: Some(120.0),
                declared: true,
            }]
        );
        assert_eq!(recorder.frames, vec![0.25]);
    }
}
